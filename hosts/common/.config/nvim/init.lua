-- Отображение и навигация
vim.opt.number = true         -- Показывать номера строк
vim.opt.relativenumber = true -- Относительные номера строк для удобства навигации
vim.opt.cursorline = true     -- Подсвечивать текущую строку
vim.opt.scrolloff = 8         -- Оставлять 8 строк сверху и снизу при прокрутке

-- Копирование-вставка
vim.opt.clipboard = "unnamedplus" -- Общий буфер обмена с системой (копируем из nvim — вставляем в другие программы)

-- Поиск
vim.opt.ignorecase = true -- Игнорировать регистр при поиске
vim.opt.smartcase = true  -- Учитывать регистр, если в поиске есть заглавные буквы
vim.opt.hlsearch = true   -- Подсвечивать найденные совпадения
vim.opt.incsearch = true  -- Показать совпадения по мере ввода

-- Отступы и табы
vim.opt.expandtab = true   -- Использовать пробелы вместо табов
vim.opt.shiftwidth = 2     -- Ширина отступа при автоматическом выравнивании
vim.opt.tabstop = 2        -- Ширина табуляции
vim.opt.smartindent = true -- Автоматический умный отступ

-- Визуальные настройки
vim.opt.termguicolors = true -- Включить 24-битные цвета (лучшее отображение тем)
vim.opt.colorcolumn = "80"   -- Вертикальная линия на 80 символе (рекомендуемый максимум длины строки)

-- Файлы и буферы
vim.opt.hidden = true   -- Позволяет переключаться между буферами без сохранения
vim.opt.autoread = true -- Автоматически перечитывать файл, если он был изменён вне Neovim

-- Интерфейс
vim.opt.splitright = true -- Вертикальный разрез новых окон справа
vim.opt.splitbelow = true -- Горизонтальный разрез новых окон снизу
vim.opt.wrap = false      -- Отключить перенос строк

-- Работа с обменом
vim.opt.mouse = "a" -- Включить мышь во всех режимах

-- Производительность
vim.opt.updatetime = 300 -- Время ожидания (ms) для событий CursorHold (например, для автосохранения)

-- Прочее
vim.g.mapleader = " " -- Установить <leader> на пробел для собственных горячих клавиш
